//! Virtual-key codes that the shortcut hook and the typing of the text share.

/// Shift, Ctrl, Alt, and Win: the generic, left, and right codes.
pub const MODIFIERS: [u16; 11] = [
    0x10, 0x11, 0x12, 0x5B, 0x5C, 0xA0, 0xA1, 0xA2, 0xA3, 0xA4, 0xA5,
];

pub fn is_modifier(vk: u16) -> bool {
    MODIFIERS.contains(&vk)
}

/// The mark on each key event that TDT sends. The keyboard hook passes
/// these events on, so the typed text cannot start a recording. Events from
/// other programs (a remap tool, a remote desktop) have another mark.
pub const OWN_INPUT: usize = 0x5444_5401;

/// macOS key codes (`kVK_*`, ANSI layout positions) for the virtual-key
/// codes above. The settings file keeps the virtual-key code on every
/// system, so a shortcut reads the same on Windows and on macOS.
#[cfg(target_os = "macos")]
pub mod mac {
    /// (virtual-key code, macOS key code).
    #[rustfmt::skip]
    const TABLE: &[(u16, u16)] = &[
        // Letters.
        (0x41, 0x00), (0x53, 0x01), (0x44, 0x02), (0x46, 0x03), (0x48, 0x04),
        (0x47, 0x05), (0x5A, 0x06), (0x58, 0x07), (0x43, 0x08), (0x56, 0x09),
        (0x42, 0x0B), (0x51, 0x0C), (0x57, 0x0D), (0x45, 0x0E), (0x52, 0x0F),
        (0x59, 0x10), (0x54, 0x11), (0x4F, 0x1F), (0x55, 0x20), (0x49, 0x22),
        (0x50, 0x23), (0x4C, 0x25), (0x4A, 0x26), (0x4B, 0x28), (0x4E, 0x2D),
        (0x4D, 0x2E),
        // Digits.
        (0x31, 0x12), (0x32, 0x13), (0x33, 0x14), (0x34, 0x15), (0x36, 0x16),
        (0x35, 0x17), (0x39, 0x19), (0x37, 0x1A), (0x38, 0x1C), (0x30, 0x1D),
        // Punctuation.
        (0xBB, 0x18), (0xBD, 0x1B), (0xDD, 0x1E), (0xDB, 0x21), (0xDE, 0x27),
        (0xBA, 0x29), (0xDC, 0x2A), (0xBC, 0x2B), (0xBF, 0x2C), (0xBE, 0x2F),
        (0xC0, 0x32),
        // Named keys.
        (0x0D, 0x24), (0x09, 0x30), (0x20, 0x31), (0x08, 0x33), (0x1B, 0x35),
        // Function keys F1 to F20.
        (0x70, 0x7A), (0x71, 0x78), (0x72, 0x63), (0x73, 0x76), (0x74, 0x60),
        (0x75, 0x61), (0x76, 0x62), (0x77, 0x64), (0x78, 0x65), (0x79, 0x6D),
        (0x7A, 0x67), (0x7B, 0x6F), (0x7C, 0x69), (0x7D, 0x6B), (0x7E, 0x71),
        (0x7F, 0x6A), (0x80, 0x40), (0x81, 0x4F), (0x82, 0x50), (0x83, 0x5A),
        // Modifiers: Command is the Win key of the binding.
        (0x5B, 0x37), (0x5C, 0x36), (0xA0, 0x38), (0xA1, 0x3C), (0xA4, 0x3A),
        (0xA5, 0x3D), (0xA2, 0x3B), (0xA3, 0x3E),
    ];

    pub const RETURN: u16 = 0x24;
    pub const TAB: u16 = 0x30;

    pub fn vk_of(keycode: u16) -> Option<u16> {
        TABLE
            .iter()
            .find(|(_, key)| *key == keycode)
            .map(|(vk, _)| *vk)
    }

    pub fn keycode_of(vk: u16) -> Option<u16> {
        TABLE
            .iter()
            .find(|(code, _)| *code == vk)
            .map(|(_, key)| *key)
    }

    #[cfg(test)]
    mod tests {
        use super::*;

        #[test]
        fn table_is_one_to_one() {
            for (vk, key) in TABLE {
                assert_eq!(vk_of(*key), Some(*vk), "key code {key:#04X}");
                assert_eq!(keycode_of(*vk), Some(*key), "virtual key {vk:#04X}");
            }
        }
    }
}
